const { initDb, getDb } = require('./db/database');

async function addMultiLineEpicDescriptions() {
  await initDb();
  const db = getDb();

  console.log('=== 📝 ثبت توضیحات مفصل و چند خطی برای اپیک‌های اصلی سیستم (Jira Epics) ===\n');

  const epicDescriptions = {
    'ORD-1': `این اپیک شامل فاز جامع استقرار کلاستر کوبرنتیز و زیرساخت دواپس تیم عملیات می‌باشد.
محورهای اصلی این اپیک:
۱. پیاده‌سازی و راه‌اندازی شبکه K8s به همراه اینگرس کنترلرها و بالانسر بار متمرکز.
۲. پیکربندی پایش متمرکز منابع با Prometheus و ساخت داشبوردهای Grafana.
۳. ایجاد پایپ‌لاین‌های خودکار GitOps بر پایه ArgoCD جهت اتوماسیون فرایند دپلی برنامه‌ها.`,

    'ORD-5': `پروژه پیاده‌سازی سرویس متمرکز لاگینگ و مانیتورینگ سیستم‌های زیرساختی.
شامل موارد زیر:
- راه‌اندازی پشته ELK/Loki جهت جمع‌آوری متمرکز لاگ‌های پلتفرم.
- تعریف هشدارهای پیشگیرانه خودکار روی کانال‌های ارتباطی تیم.`,

    'ORD-9': `پروژه ارتقا و بهینه‌سازی دیتابیس‌های عملیاتی پلتفرم و مدیریت ذخیره‌سازی Ceph.
اهداف عملیاتی:
- راه‌اندازی کلاستر PostgreSQL HA جهت پایداری بالا در ترافیک سنگین.
- تست و استقرار ذخیره‌ساز توزیع شده Ceph جهت پشتیبان‌گیری خودکار.`,

    'ORD-13': `این اپیک شامل فاز جامع ارتقا و خودکارسازی امنیت ابری کلاسترها می‌باشد. 
اهداف اصلی این پروژه عبارتند از:
۱. پیاده‌سازی ابزار Trivy برای اسکن خودکار تصاویر داکر و شناسایی آسیب‌پذیری‌های CVE بالا و کریتیکال در پایپ‌لاین CI/CD.
۲. طراحی و استقرار کلاستر متمرکز HashiCorp Vault جهت مدیریت امن کلیدها، گواهی‌نامه‌های SSL و سرویس مدیریت اسرار (Secrets Engine).
۳. اتوماسیون کامل تست‌های تحلیل استاتیک کد (SAST) با ابزار SonarQube به همراه اتصال هوشمند به مخزن گیت‌هاب تیم توسعه.
۴. پشتیبانی عملیاتی، تدوین مستندات امنیتی تحویل سیستم و اجرای مانورهای دوره‌ای تست بازگردانی بک‌آپ سرورهای Vault.`,

    'ORD-17': `پروژه تحقیق و توسعه ماژول‌های هوش مصنوعی و پردازش زبان طبیعی روی کلاستر GPU.
شامل:
- دیپلوی مدل‌های زبانی متمرکز جهت آنالیز متون و گزارش‌گیری خودکار.
- بهینه‌سازی مصرف منابع GPU و تست‌های پایداری سیستم در بار کاری بالا.`
  };

  for (const [id, desc] of Object.entries(epicDescriptions)) {
    db.prepare('UPDATE projects SET description = ? WHERE id = ?').run(desc, id);
    console.log(`✅ توضیحات مفصل و چندخطی برای اپیک ${id} ثبت شد.`);
  }

  console.log('\n✨ تمامی توضیحات اپیک‌ها در دیتابیس به‌روزرسانی شدند.');
}

addMultiLineEpicDescriptions().catch(console.error);
